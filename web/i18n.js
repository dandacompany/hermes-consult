export const messages = { en, ko };

/** BCP 47 tag → supported UI locale. Korean for ko*, English otherwise. */
export function pickLocale(tag) {
  return /^ko(?:-|$)/i.test(String(tag || "")) ? "ko" : "en";
}

export function t(locale, key, ...values) {
  const text = (messages[locale] ?? en)[key] ?? en[key] ?? key;
  return text.replace(/\{(\d+)\}/g, (_, n) => String(values[Number(n)] ?? ""));
}

/** A relay error body ({ code, error }) as a localized Error. */
export function relayError(locale, body) {
  const code = body?.code;
  return Error(code && code in en ? t(locale, code) : body?.error || t(locale, "errGeneric"));
}

/** Fill data-i18n / data-i18n-html / data-i18n-<attribute> elements from the catalog. */
export function applyI18n(locale, root = document) {
  document.documentElement.lang = locale;
  for (const el of root.querySelectorAll("[data-i18n]"))
    el.textContent = t(locale, el.dataset.i18n);
  for (const el of root.querySelectorAll("[data-i18n-html]"))
    el.innerHTML = t(locale, el.dataset.i18nHtml); // trusted catalog markup only
  for (const attr of ["placeholder", "aria-label", "title"]) {
    const data = "data-i18n-" + attr;
    for (const el of root.querySelectorAll(`[${data}]`))
      el.setAttribute(attr, t(locale, el.getAttribute(data)));
  }
}
